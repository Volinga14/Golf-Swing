"""Evaluate Swing Lab phase detection corrections.

Reads JSON files generated by /api/training/submit and reports mean absolute
error by phase. This is the first benchmark layer before auto-publishing a new
model.

Usage:
  python training/evaluate_engine.py --training-dir online-engine/storage/training
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path
from statistics import mean

PHASES = ["address", "takeaway", "top", "impact", "finish"]


def load_corrections(path: Path):
    data = json.loads(path.read_text(encoding="utf-8"))
    corrections = data.get("autoVsFinalCorrections") or data.get("corrections") or []
    out = []
    for item in corrections:
        phase = item.get("phase")
        if phase not in PHASES:
            continue
        delta = item.get("deltaSeconds")
        if isinstance(delta, (int, float)):
            out.append((phase, float(delta), data.get("engineVersion") or data.get("autoDetection", {}).get("provider")))
    return out


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--training-dir", default="online-engine/storage/training")
    parser.add_argument("--max-pass-error", type=float, default=0.12, help="Target average error in seconds for Top/Impact.")
    args = parser.parse_args()
    root = Path(args.training_dir)
    files = sorted(root.glob("*.json"))
    phase_abs = {p: [] for p in PHASES}
    for file in files:
        for phase, delta, _ in load_corrections(file):
            phase_abs[phase].append(abs(delta))
    print(f"Training sessions: {len(files)}")
    overall = []
    for phase in PHASES:
        vals = phase_abs[phase]
        if vals:
            overall.extend(vals)
            print(f"{phase:9s} MAE: {mean(vals):.3f}s  n={len(vals)}")
        else:
            print(f"{phase:9s} MAE: --      n=0")
    if overall:
        print(f"Overall MAE: {mean(overall):.3f}s")
    top_impact = phase_abs["top"] + phase_abs["impact"]
    if top_impact and mean(top_impact) <= args.max_pass_error:
        print("PASS: Top/Impact benchmark target reached.")
        return 0
    print("REVIEW: Top/Impact benchmark still needs improvement.")
    return 1


if __name__ == "__main__":
    raise SystemExit(main())
